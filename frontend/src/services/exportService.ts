import { FullInscriptionRecord } from '../types/inscription';

class ExportService {
  /**
   * Generates structured JSON schema export
   */
  exportToJSON(record: FullInscriptionRecord): string {
    const exportData = {
      $schema: 'https://lipika.ai/schemas/v1/inscription.json',
      metadata: { ...record.metadata },
      enhancement_parameters: { ...record.enhancement },
      ocr_results: {
        total_glyphs: record.ocr.totalGlyphsDetected,
        average_confidence: record.ocr.averageConfidence,
        raw_brahmi_line: record.ocr.rawBrahmiLine,
        characters: record.ocr.segments.map((seg) => ({
          index: seg.id,
          brahmi: seg.correctedChar || seg.brahmiChar,
          unicode_hex: seg.unicodeHex,
          iast: seg.phoneticIAST,
          devanagari: seg.devanagariEquiv,
          confidence: seg.confidence,
          is_corrected: seg.isCorrected || false,
          notes: seg.notes || '',
          bounding_box: {
            x_pct: seg.x,
            y_pct: seg.y,
            w_pct: seg.width,
            h_pct: seg.height,
          },
          alternatives: seg.alternatives,
        })),
      },
      transliteration: { ...record.transliteration },
      translation: { ...record.translation },
      verification_status: { ...record.verification },
      exported_timestamp: new Date().toISOString(),
    };
    return JSON.stringify(exportData, null, 2);
  }

  /**
   * Generates plain text / Markdown export
   */
  exportToTXT(record: FullInscriptionRecord): string {
    const timeStr = new Date().toLocaleString();
    return `================================================================================
LIPIKA AI — ANCIENT BRAHMI EPIGRAPHICAL RESEARCH REPORT
================================================================================

RECORD METADATA:
  Catalog ID:        ${record.metadata.corpusCatalogId}
  Title:             ${record.metadata.title}
  Provenance:        ${record.metadata.provenance}
  Site Location:     ${record.metadata.siteLocation}
  Current Location:  ${record.metadata.currentLocation}
  Period & Dynasty:  ${record.metadata.period} (${record.metadata.dynasty})
  Estimated Century: ${record.metadata.estimatedCentury}
  Material & Size:   ${record.metadata.material} (${record.metadata.dimensions})
  Language & Script: ${record.metadata.language} / ${record.metadata.script}
  CII Volume Ref:    ${record.metadata.ciiVolumeRef || 'N/A'}
  Upload Timestamp:  ${record.metadata.uploadTimestamp}
  Export Timestamp:  ${timeStr}

HUMAN VERIFICATION AUDIT:
  Status:            ${record.verification.isVerified ? 'HUMAN VERIFIED' : 'PENDING REVIEW'}
  Verified By:       ${record.verification.verifiedBy || 'N/A'}
  Verification Date: ${record.verification.verificationDate || 'N/A'}
  Corrections Logged:${record.verification.correctionsCount}
  Audit Remarks:     ${record.verification.verificationNotes || 'None'}

OCR CHARACTER RECOGNITION SUMMARY:
  Total Glyphs:      ${record.ocr.totalGlyphsDetected}
  Average Conf:      ${record.ocr.averageConfidence.toFixed(1)}%
  Raw Brahmi Stream: ${record.ocr.rawBrahmiLine}

DETAILED CHARACTER PREDICTIONS:
${record.ocr.segments
  .map(
    (s, idx) =>
      `  [Character ${String(idx + 1).padStart(2, '0')}] Glyph: ${s.correctedChar || s.brahmiChar} | IAST: ${s.phoneticIAST} | Dev: ${s.devanagariEquiv} | Hex: ${s.unicodeHex} | Conf: ${s.confidence.toFixed(1)}%${s.isCorrected ? ' (Corrected)' : ''}`
  )
  .join('\n')}

TRANSLITERATION:
  IAST Stream:       ${record.transliteration.iastText}
  Devanagari Stream: ${record.transliteration.devanagariText}

TRANSLATIONS:
  English:
  "${record.translation.englishTranslation}"

  Hindi (हिंदी):
  "${record.translation.hindiTranslation}"

CONTEXTUAL & HISTORICAL EXPLANATION:
  Reign of:          ${record.translation.historicalContext.reignOf}
  Summary:           ${record.translation.historicalContext.summary}
  Geopolitical:      ${record.translation.historicalContext.geopoliticalSignificance}

================================================================================
Generated by Lipika AI Epigraphy Engine v1.0
`;
  }

  /**
   * Generates EpiDoc TEI-XML export
   */
  exportToTEIXML(record: FullInscriptionRecord): string {
    return `<?xml version="1.0" encoding="UTF-8"?>
<TEI xmlns="http://www.tei-c.org/ns/1.0" xml:space="preserve">
  <teiHeader>
    <fileDesc>
      <titleStmt>
        <title>${record.metadata.title}</title>
        <editor role="epigraphist">${record.verification.verifiedBy || 'Lipika AI Epigraphy Engine'}</editor>
      </titleStmt>
      <publicationStmt>
        <authority>Lipika AI Digital Humanities Archive</authority>
        <idno type="CII">${record.metadata.corpusCatalogId}</idno>
        <date>${new Date().toISOString().split('T')[0]}</date>
      </publicationStmt>
      <sourceDesc>
        <msDesc>
          <msIdentifier>
            <repository>${record.metadata.currentLocation}</repository>
            <idno>${record.metadata.corpusCatalogId}</idno>
          </msIdentifier>
          <history>
            <origin>
              <origPlace>${record.metadata.siteLocation}</origPlace>
              <origDate>${record.metadata.estimatedCentury}</origDate>
            </origin>
          </history>
        </msDesc>
      </sourceDesc>
    </fileDesc>
  </teiHeader>
  <text>
    <body>
      <div type="edition" xml:lang="pra-Brah">
        <ab>${record.ocr.rawBrahmiLine}</ab>
      </div>
      <div type="transliteration" xml:lang="sa-Latn">
        <ab>${record.transliteration.iastText}</ab>
      </div>
      <div type="translation" xml:lang="en">
        <p>${record.translation.englishTranslation}</p>
      </div>
      <div type="translation" xml:lang="hi">
        <p>${record.translation.hindiTranslation}</p>
      </div>
    </body>
  </text>
</TEI>`;
  }

  /**
   * Generates formatted PDF Markdown report
   */
  exportToPDFReport(record: FullInscriptionRecord): string {
    return this.exportToTXT(record);
  }

  /**
   * Triggers client file download
   */
  downloadFile(filename: string, content: string, mimeType: string): void {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }
}

export const exportService = new ExportService();
